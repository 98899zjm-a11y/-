"""Guest-only explicit source/data packaging; never launches a program or writes owner."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import types

ROOT = Path(__file__).resolve().parent.parent
RESULTS = Path('C:/xjy-results')
_context = None
_seals = None


def configure(contract_sha, materials_sha, package_evidence_sha=None):
    global _context, _seals
    if os.name != 'nt' or os.path.normcase(str(ROOT)) != os.path.normcase('C:/xjy-work/xjy-web-stage1'):
        raise RuntimeError('Fixed actual Guest required; no Host packaging')
    if not re.fullmatch('[0-9a-f]{64}', materials_sha or ''):
        raise RuntimeError('Root-reviewed materials SHA required')
    material_body = (ROOT/'audit-tools/next-ui-materials.json').read_bytes()
    if hashlib.sha256(material_body).hexdigest() != materials_sha:
        raise RuntimeError('Materials changed before common helper load')
    pins = json.loads(material_body).get('harnessPins') or {}
    checked_bodies = {}
    for filename in ('next-ui-common.py', 'next-ui-package.py'):
        body = (ROOT/'audit-tools'/filename).read_bytes()
        if hashlib.sha256(body).hexdigest() != pins.get('audit-tools/'+filename):
            raise RuntimeError('Root must seal next UI packaging helpers')
        checked_bodies[filename] = body
    file = ROOT/'audit-tools/next-ui-common.py'
    module = types.ModuleType('next_ui_common')
    module.__file__ = str(file)
    exec(compile(checked_bodies['next-ui-common.py'], str(file), 'exec'), module.__dict__)
    _context = (module, *module.load_inputs(contract_sha, materials_sha))
    _seals = contract_sha, materials_sha, package_evidence_sha
    return _context


def context():
    if _context is None:
        raise RuntimeError('Explicit Root seals and actual inputs required first')
    return _context


def ordinary(*args, **kwargs): return context()[0].ordinary(*args, **kwargs)
def stable_bytes(*args, **kwargs): return context()[0].stable_bytes(*args, **kwargs)
def read_json(*args, **kwargs): return context()[0].read_json(*args, **kwargs)
def digest(body): return hashlib.sha256(body).hexdigest()
def actual_guard(): return context()[0].actual_guard()
def put(*args, **kwargs): return context()[0].put(*args, **kwargs)
def load_module(*args, **kwargs): return context()[0].load_module(*args, **kwargs)


def run_root(run_id):
    if run_id != 'ui-a2':
        raise RuntimeError('Only the exact ui-a2 QA run is admitted')
    return ordinary(context()[0].BASE, missing=True)


def source_plan():
    common, proof, contract, material, build, policy = context()
    original = common.original()
    candidate, _ = original.verify_candidate()  # Unchanged reviewed old-engine/resource data check.
    engine = common.read_json(candidate/'engine-allowlist.json')
    resources = common.read_json(candidate/'release-manifest.json')
    fixed = {r['path']: r for r in resources['files'] if r['path'].startswith(('resources/print-dependencies/', 'resources/release-modules/')) or r['path'] == 'resources/app.asar.unpacked/ocr.winrt.ps1'}
    engine_rows = {r['path']: r for r in engine['files']}
    app = Path(contract['build']['appInput'])
    compiled = {r['path']: r for r in common.scan(app)}
    if not all(name in compiled for name in ('renderer-dist/index.html', 'renderer-dist/browser.html', 'renderer-dist/central.html', 'renderer-dist/print.html',
                                            'generated/business.cjs', 'generated/print-domain.cjs', 'generated/print-worker-templates.cjs', 'generated/print-worker-preload.cjs')):
        raise RuntimeError('Full fresh build4 renderer and four generated files required')
    for name in compiled:
        if not (name.startswith('renderer-dist/') or re.fullmatch(r'generated/(business|print-domain|print-worker-templates|print-worker-preload)\.cjs', name)):
            raise RuntimeError('Unexpected file in actual build4 output')
    generated = build.get('generated', [])
    if len(generated) != 4 or {Path(r['file']).name for r in generated} != {'business.cjs', 'print-domain.cjs', 'print-worker-templates.cjs', 'print-worker-preload.cjs'}:
        raise RuntimeError('Actual build4 report must identify all four generated files')
    for row in generated:
        if compiled['generated/'+Path(row['file']).name]['sha256'] != row['sha256']:
            raise RuntimeError('Actual generated byte hash differs from build4 report')
    rows = material['programFiles']
    if len(rows) > 4096 or len({r['path'].casefold() for r in rows}) != len(rows):
        raise RuntimeError('Bounded unique exact program inventory required')
    kinds = {'original-engine': set(), 'fixed-resource': set(), 'build4': set()}
    package_body = (json.dumps({'name': 'xjy-next-source-ui-qa', 'version': '1.6.0', 'private': True, 'main': 'release-entry.cjs'}, indent=2)+'\n').encode()
    for row in rows:
        if set(row) != {'path', 'source', 'kind', 'size', 'sha256'}:
            raise RuntimeError('Exact program source-row schema required')
        if type(row['size']) is not int or not 0 <= row['size'] <= 512*1024*1024 or not re.fullmatch('[0-9a-f]{64}', str(row['sha256'])):
            raise RuntimeError('Bounded exact program size/hash required')
        name = common.safe_relative(row['path'])
        kind = row['kind']
        if kind in ('original-engine', 'fixed-resource'):
            expected = (engine_rows if kind == 'original-engine' else fixed).get(name)
            if not expected or row['source'] != 'release-candidate/'+name or any(row[k] != expected[k] for k in ('size', 'sha256')):
                raise RuntimeError('Original engine/fixed-resource origin drift')
            kinds[kind].add(name)
        elif kind == 'build4':
            relative = name.removeprefix('resources/app/')
            expected = compiled.get(relative)
            if not name.startswith('resources/app/') or not expected or Path(row['source']) != app/relative or any(row[k] != expected[k] for k in ('size', 'sha256')):
                raise RuntimeError('Fresh build4 program origin drift')
            kinds[kind].add(relative)
        elif kind == 'current-runtime':
            relative = name.removeprefix('resources/app/')
            if not name.startswith('resources/app/') or relative == 'package.json' or row['source'] != 'project/desktop/'+relative or relative in compiled or re.search(r'\.(db|sqlite3?|pem|key)$', relative, re.I):
                raise RuntimeError('Explicit current runtime program source required')
        elif kind == 'qa-entry':
            if name != 'resources/app/package.json' or row['source'] is not None or row['size'] != len(package_body) or row['sha256'] != common.digest(package_body):
                raise RuntimeError('Only fixed QA package metadata may be synthesized')
            continue
        else:
            raise RuntimeError('Unknown program input kind')
        source = Path(row['source']) if kind == 'build4' else ROOT/common.safe_relative(row['source'])
        if common.hash_file(source) != {k: row[k] for k in ('size', 'sha256')}:
            raise RuntimeError('Actual program source bytes differ from Root inventory')
    if kinds['original-engine'] != set(engine_rows) or kinds['fixed-resource'] != set(fixed) or kinds['build4'] != set(compiled):
        raise RuntimeError('Partial engine/fixed resources/compiler output rejected')
    if sum(row['size'] for row in rows) > 1024*1024*1024:
        raise RuntimeError('Program tree exceeds reviewed QA byte ceiling')
    if not any(r['path'] == 'resources/app/release-entry.cjs' and r['kind'] == 'current-runtime' for r in rows) or not any(r['path'] == 'resources/app/package.json' and r['kind'] == 'qa-entry' for r in rows):
        raise RuntimeError('Real release-entry and fixed package metadata required')
    return rows, package_body


def prepare():
    common, proof, contract, material, build, policy = context()
    rows, package_body = source_plan()
    common.actual_guard()
    ordinary(common.BASE, missing=True).mkdir(parents=True, exist_ok=False)
    for row in rows:
        target = common.PROGRAM/common.safe_relative(row['path'])
        if row['kind'] == 'qa-entry':
            common.put(target, package_body)
        else:
            source = Path(row['source']) if row['kind'] == 'build4' else ROOT/row['source']
            if common.hash_file(source, target=target) != {k: row[k] for k in ('size', 'sha256')}:
                raise RuntimeError('Program input changed during preparation')
    tree = common.scan(common.PROGRAM)
    if common.tree_digest(tree) != contract['build']['newProgramTreeSha256']:
        raise RuntimeError('Actual new program tree differs from Root seal')
    evidence = {'version': 1, 'purpose': 'next-source-ui-qa', 'runId': 'ui-a2', 'actualContext': proof,
                'program': str(common.PROGRAM), 'exactAppInput': contract['build']['appInput'],
                'buildReportSha256': contract['build']['reportSha256'], 'sourceHashes': build['sourceHashes'],
                'gatewaySourceSha256': contract['build']['gatewaySourceSha256'], 'gatewayOutputSha256': contract['build']['gatewayOutputSha256'],
                'programTreeSha256': common.tree_digest(tree), 'files': tree, 'origins': rows,
                'programExecuted': False, 'productionTouched': False, 'unsealedQaOnly': True}
    common.put(common.BASE/'package-evidence.json', (json.dumps(evidence, ensure_ascii=True, indent=2)+'\n').encode())
    return evidence


def verify(run_id):
    common, proof, contract, material, build, policy = context()
    run_root(run_id)
    common.actual_guard()
    source_plan()  # Recheck real origins/complete old engine; metadata does not self-certify.
    evidence = common.sealed(common.BASE/'package-evidence.json', _seals[2])
    if evidence.get('purpose') != 'next-source-ui-qa' or evidence.get('runId') != 'ui-a2' or Path(evidence.get('program', '')) != common.PROGRAM or Path(evidence.get('exactAppInput', '')) != Path(contract['build']['appInput']) or evidence.get('buildReportSha256') != contract['build']['reportSha256'] or evidence.get('sourceHashes') != build['sourceHashes'] or evidence.get('origins') != material['programFiles']:
        raise RuntimeError('Independent package evidence is not this build4 capsule')
    tree = common.scan(common.PROGRAM)
    if tree != evidence.get('files') or common.tree_digest(tree) != contract['build']['newProgramTreeSha256']:
        raise RuntimeError('Complete new program tree drift')
    return evidence


def verify_handoff():
    common, proof, contract, material, build, policy = context()
    journal = common.read_json(common.JOURNAL_ROOT/'journal.json')
    old_body = common.stable_bytes(common.JOURNAL_ROOT/'old-owner.json')
    owner_body = common.stable_bytes(common.OWNER)
    profile_stat = common.ordinary(common.PROFILE).stat()
    expected = {'version': 1, 'purpose': 'current-source-ui-qa', 'namespace': contract['namespace'], 'runId': 'ui-a2'}
    if (journal.get('purpose') != 'next-ui-owner-handoff' or journal.get('phase') != 'committed'
            or journal.get('contractSha256') != _seals[0] or journal.get('materialsSha256') != _seals[1]
            or journal.get('packageEvidenceSha256') != _seals[2] or common.digest(old_body) != contract['oldOwnerSha256']
            or common.digest(owner_body) != journal.get('newOwnerSha256') or json.loads(owner_body) != expected
            or journal.get('profileIdentity') != [profile_stat.st_dev, profile_stat.st_ino]
            or journal.get('newOwnerIdentity') != list(common.identity(common.ordinary(common.OWNER).stat()))):
        raise RuntimeError('Exact completed QA handoff is required; unknown owner cannot be adopted')
    return journal


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument('--contract-sha256', required=True)
    parser.add_argument('--materials-sha256', required=True)
    args = parser.parse_args()
    configure(args.contract_sha256, args.materials_sha256)
    record = prepare()
    print(json.dumps({'prepared': True, 'programTreeSha256': record['programTreeSha256'],
                      'packageEvidenceSha256': digest(stable_bytes(context()[0].BASE/'package-evidence.json')),
                      'programExecuted': False, 'ownerChanged': False}))
