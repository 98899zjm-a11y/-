'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
test('global guard prevents native IO, SQLite escape, shell and public sockets before business imports',async()=>{
 const file=path.join(root,'data','guard-tests','test.sqlite'),outside=path.join(root,'tests','fake-external-files','sentinel.txt');
 fs.mkdirSync(path.dirname(file),{recursive:true});
 fs.mkdirSync(path.dirname(outside),{recursive:true});if(!fs.existsSync(outside))fs.writeFileSync(outside,'SYNTHETIC-ONLY');const before=fs.readFileSync(outside);
 const api=require('../stage1/io-guard.cjs');
 assert.equal(typeof api.install,'function','global guard bootstrap is required');
 const policy=api.install({root,writeDirs:['data','config','cache','logs','runtime','backups'].map(x=>path.join(root,x)),readDirs:[],childPrograms:[]});
 assert.throws(()=>fs.readFileSync('F:\\鑫金源珠宝资料\\工作室数据\\jewelry.sqlite'),/ISOLATION/);
 assert.throws(()=>fs.writeFileSync(path.join(root,'project','tamper.txt'),'x'),/ISOLATION/);
 await assert.rejects(fs.promises.readFile('F:\\鑫金源珠宝资料\\内帐\\ledger.db'),/ISOLATION/);
 assert.throws(()=>fs.createWriteStream(outside),/ISOLATION/);
 assert.throws(()=>fs.openSync(outside,'r+'),/ISOLATION/);
 assert.throws(()=>fs.symlinkSync(outside,path.join(root,'data','redirect')),/ISOLATION/);
 const sqlite=require('node:sqlite');
 assert.throws(()=>new sqlite.DatabaseSync('F:\\鑫金源珠宝资料\\库管\\stockcheck.db'),/ISOLATION/);
 const db=new sqlite.DatabaseSync(file);db.exec('CREATE TABLE IF NOT EXISTS t(value INTEGER); INSERT INTO t VALUES(42);');
 assert.equal(db.prepare('SELECT max(value) AS value FROM t').get().value,42);
 assert.throws(()=>db.exec("ATTACH DATABASE 'F:/鑫金源珠宝资料/内帐/ledger.db' AS external"),/ISOLATION|authorized/);
 assert.throws(()=>db.prepare('VACUUM INTO ?').run(outside),/ISOLATION|authorized/);
 assert.throws(()=>db.loadExtension(outside),/ISOLATION/);
 db.setAuthorizer(()=>sqlite.constants.SQLITE_OK);
 assert.throws(()=>db.exec("ATTACH DATABASE 'F:/bad.sqlite' AS external"),/ISOLATION|authorized/);
 db.close();
 const cp=require('node:child_process');assert.throws(()=>cp.exec('cmd /c echo unsafe'),/ISOLATION/);
 assert.throws(()=>cp.spawn(process.execPath,['-e','1']),/ISOLATION/);
 const net=require('node:net'),server=net.createServer();
 assert.throws(()=>server.listen(0,'0.0.0.0'),/ISOLATION/);assert.throws(()=>server.listen(31831,'127.0.0.1'),/ISOLATION/);
 assert.throws(()=>net.connect(443,'example.com'),/ISOLATION/);
 await new Promise((resolve,reject)=>server.once('error',reject).listen(0,'127.0.0.1',resolve));await new Promise(r=>server.close(r));
 assert.deepEqual(fs.readFileSync(outside),before);
 assert.equal(policy.installed,true);
});
